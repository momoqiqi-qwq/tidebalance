import assert from 'node:assert/strict';
import * as S from '../src/store.js';
const memory = new Map();
globalThis.localStorage = { getItem: k => memory.get(k), setItem: (k, v) => memory.set(k, v) };
await S.initStore({ tasks: [], blocks: [], settings: {}, plugins: {} });
const t = S.addTask({ title: '排程测试', estMin: 60 });
const first = S.placeTask(t, '2026-09-09');
assert.equal(first.start, '07:00');
S.placeTask(t, '2026-09-10');
S.placeTask(t, '2026-09-09');
assert.equal(S.getState().blocks.length, 2, '重新安排不重复，保留其他日期');
const before = JSON.stringify(S.getState().blocks);
assert.throws(() => S.placeTask(t, '2026-09-09', 1430));
assert.equal(JSON.stringify(S.getState().blocks), before, '超出午夜不丢旧安排');
S.addBlock({ date: '2026-09-09', start: '09:00', durMin: 60 });
const conflictBefore = JSON.stringify(S.getState().blocks);
assert.throws(() => S.placeTask(t, '2026-09-09', 550));
assert.equal(JSON.stringify(S.getState().blocks), conflictBefore, '冲突不修改数据');
S.updateTask(t.id, { title: '修改标题' });
assert.ok(S.getState().blocks.filter(b => b.taskId === t.id).every(b => b.title === '修改标题'));
const undo = S.deleteTaskUndoable(t.id);
assert.equal(S.taskById(t.id), undefined);
assert.equal(S.getState().blocks.filter(b => b.taskId === t.id).length, 0);
undo(); undo();
assert.equal(S.getState().tasks.length, 1);
assert.equal(S.getState().blocks.filter(b => b.taskId === t.id).length, 2);
S.toggleTask(t.id);
assert.equal(S.taskById(t.id).done, true);
await S.saveNow();
await S.initStore({});
assert.equal(S.taskById(t.id).title, '修改标题');
assert.equal(S.getState().blocks.length, 3);
console.log('PASS: 自动排程、幂等重排、跨日保留、午夜边界、冲突回滚、标题同步、完整撤销、完成与持久化');
